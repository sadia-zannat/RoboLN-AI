"""Raspberry Pi / generic Python controller adapter. Does not operate actuators.

Read a measurement JSON object from a sensor producer, check the enrolled origin,
then submit it over authenticated HTTP. HTTPS is mandatory except loopback.
No values are invented and no device tokens are written to logs.
"""
import argparse,json,os,sys,uuid
from datetime import datetime,timezone
from urllib.parse import urlparse
from urllib.request import Request,urlopen
from urllib.error import HTTPError,URLError

def send(base,token,method,path,payload=None):
    req=Request(base.rstrip('/')+path,data=json.dumps(payload).encode() if payload is not None else None,
        headers={'Authorization':'Bearer '+token,'Content-Type':'application/json'},method=method)
    try:
        with urlopen(req,timeout=15) as response:return json.load(response)
    except HTTPError as e:
        raise RuntimeError(f'RoboLN rejected the request (HTTP {e.code}); inspect device status and packet schema.') from None
    except URLError:raise RuntimeError('Cannot reach RoboLN. TLS verification remains enabled.') from None

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--input',required=True,help='JSON file containing measurements and optional event/observed_at; generated by your actual sensor producer')
    parser.add_argument('--expected-mode',required=True,choices=['LIVE_REAL','SIMULATION']);args=parser.parse_args()
    base=os.environ.get('ROBOLN_API_URL','http://127.0.0.1:8000');token=os.environ.get('ROBOLN_DEVICE_TOKEN','')
    url=urlparse(base)
    if url.scheme!='https' and not(url.scheme=='http' and url.hostname in ('127.0.0.1','localhost')):raise RuntimeError('Use HTTPS outside localhost')
    if not token:raise RuntimeError('Set ROBOLN_DEVICE_TOKEN on this controller')
    device=send(base,token,'GET','/api/device/status')
    if device['mode']!=args.expected_mode:raise RuntimeError('Enrolled origin does not match the expected mode. No packet sent.')
    with open(args.input,encoding='utf-8') as f:packet=json.load(f)
    if not isinstance(packet,dict) or not isinstance(packet.get('measurements',[]),list):raise RuntimeError('Input must be a measurement packet object')
    packet.setdefault('packet_id',str(uuid.uuid4()));packet.setdefault('observed_at',datetime.now(timezone.utc).isoformat())
    result=send(base,token,'POST','/api/device/telemetry',packet)
    print(json.dumps({'accepted':result['accepted'],'origin':result['origin'],'packet_id':result['packet_id']}))
if __name__=='__main__':
    try:main()
    except (RuntimeError,ValueError,OSError) as e:print(str(e),file=sys.stderr);raise SystemExit(1)
